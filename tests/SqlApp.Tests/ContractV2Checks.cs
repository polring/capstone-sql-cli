using System.Buffers.Binary;
using System.Globalization;
using System.Text;
using SqlApp.Interop.SqlEngine;
using SqlApp.Services;

internal static class ContractV2Checks
{
    internal static void Verify(string fixtureRoot, string tempDirectory)
    {
        foreach (string suite in new[] { "base", "custom_layout", "no_seeds", "many_seeds" })
        {
            string directory = Path.Combine(fixtureRoot, suite);
            string path = Path.Combine(directory, "model.gguf");
            var tokenizer = GgufContract.ReadTokenizer(path);
            using var model = SqlModel.Open(path);
            int count = 0;
            foreach (string line in File.ReadLines(Path.Combine(directory, "cases.txt")))
            {
                if (line.Length == 0 || line.StartsWith('#')) continue;
                string[] fields = line.Split('\t');
                string name = $"{suite} case {++count} ({fields[0]})";
                switch (fields[0])
                {
                    case "encode" when fields.Length == 3:
                        var encoded = tokenizer.Encode(HexText(fields[1]));
                        Require(encoded.SequenceEqual(Ints(fields[2])), $"{name}: wrong token IDs");
                        break;
                    case "logits" when fields.Length == 3:
                        int[] tokens = Ints(fields[1]);
                        float[] actual = new float[tokenizer.VocabSize];
                        double elapsed = model.Forward(tokens, tokens.Length, actual);
                        Require(double.IsFinite(elapsed) && elapsed > 0, $"{name}: missing forward time");
                        var expected = fields[2].Split(' ').Select(s => double.Parse(s, CultureInfo.InvariantCulture)).ToArray();
                        Require(expected.Length == actual.Length, $"{name}: logits width");
                        for (int i = 0; i < expected.Length; i++)
                            Require(Math.Abs(actual[i] - expected[i]) <= 2e-5 + 2e-5 * Math.Abs(expected[i]),
                                $"{name}: logits[{i}] expected {expected[i]}, got {actual[i]}");
                        break;
                    case "generate" when fields.Length == 5:
                        int limit = int.Parse(fields[1], CultureInfo.InvariantCulture);
                        string question = HexText(fields[2]);
                        var result = TokenGeneration.Generate(model, tokenizer, question, limit);
                        byte[] expectedBytes = Convert.FromHexString(fields[3]);
                        if (suite == "base" && question == "HELLO STOCK")
                        {
                            // The upstream exporter recorded this row after preparing "hello stock".
                            var upstream = TokenGeneration.Generate(model, tokenizer, "hello stock", limit);
                            Require(upstream.Bytes.AsSpan().SequenceEqual(expectedBytes) && upstream.StopReason == fields[4],
                                $"{name}: upstream prepared-input reference");
                            // Full-prefix reference for literal ASCII "HELLO STOCK" (BOS=257, SEP=259).
                            expectedBytes = "[[["u8.ToArray();
                        }
                        Require(result.Bytes.AsSpan().SequenceEqual(expectedBytes), $"{name}: generated bytes");
                        Require(result.StopReason == fields[4], $"{name}: expected {fields[4]}, got {result.StopReason}");
                        bool noForward = limit == 0 || tokenizer.EncodePrompt(question).Length == tokenizer.Context;
                        Require(double.IsFinite(result.ComputeTimeMs) &&
                            (noForward ? result.ComputeTimeMs == 0 : result.ComputeTimeMs > 0), $"{name}: compute time");
                        break;
                    default:
                        throw new InvalidDataException($"{name}: unrecognized fixture row");
                }
            }
            Require(count > 0, $"Empty fixture suite {suite}");
            Console.WriteLine($"{suite}: verified {count} reference cases");
        }

        string baseModel = Path.Combine(fixtureRoot, "base", "model.gguf");
        VerifyTokenizerRejection(baseModel, tempDirectory);
        VerifyGenerationRules(baseModel);
    }

    private static void VerifyGenerationRules(string path)
    {
        var tokenizer = GgufContract.ReadTokenizer(path);
        int[] prompt = tokenizer.EncodePrompt("Show <TABLE1.COL2>");
        Require(prompt[0] == 257 && prompt[^1] == 259 &&
            tokenizer.Decode(prompt.AsSpan(1, prompt.Length - 2)).AsSpan().SequenceEqual("Show <TABLE1.COL2>"u8),
            "Preserve natural-language and tag casing inside the model's BOS/SEP tokens");
        var mask = tokenizer.DecodableMask;
        Require(mask.Length == tokenizer.VocabSize && mask[0] != 0 && mask[255] != 0 &&
            mask[260] != 0 && mask[305] != 0, "Base byte, seed and merge IDs can be emitted");
        Require(mask[256] == 0 && mask[257] == 0 && mask[258] == 0 && mask[259] == 0 && mask[306] == 0,
            "Special and unassigned IDs have no decoded bytes");

        using var model = SqlModel.Open(path);
        var eosOnly = model.GenerateIds(tokenizer.EncodePrompt("hello"), new byte[tokenizer.VocabSize],
            tokenizer.EosId, 1, new int[1]);
        Require(eosOnly.Count == 0 && eosOnly.StopReason == "eos" && eosOnly.ComputeTimeMs > 0,
            "Native generation honors the supplied output mask and omits EOS from output");
        string fullContext = new('1', tokenizer.Context - 2);
        var noBudget = TokenGeneration.Generate(model, tokenizer, fullContext, 0);
        Require(noBudget is { StopReason: "max_new_tokens", ComputeTimeMs: 0, Bytes.Length: 0 },
            "Zero budget wins over full context without evaluating the model");
        foreach (string invalid in new[] { "한", "x\0y", new string('1', tokenizer.Context - 1) })
        {
            try
            {
                TokenGeneration.Generate(model, tokenizer, invalid, 1);
            }
            catch (Exception ex) when (ex is ArgumentException or InvalidDataException or InvalidOperationException)
            {
                continue;
            }
            throw new InvalidOperationException($"Accepted invalid prompt of length {invalid.Length}");
        }
        var retry = TokenGeneration.Generate(model, tokenizer, "hello", 1);
        Require(retry.Bytes.AsSpan().SequenceEqual(new byte[] { 0xab }), "Failed input leaves loaded model usable");
        // The same weight handle can serve overlapping sentences. Their KV state must stay local.
        Parallel.Invoke(
            () => Require(TokenGeneration.Generate(model, tokenizer, "hello", 5).Bytes.AsSpan()
                .SequenceEqual(Convert.FromHexString("abd1d160cc")), "Independent cache for first sentence"),
            () => Require(TokenGeneration.Generate(model, tokenizer, "hello stock", 3).Bytes.AsSpan()
                .SequenceEqual(Convert.FromHexString("3cd13d")), "Independent cache for second sentence"));
    }

    private static void VerifyTokenizerRejection(string baseModel, string tempDirectory)
    {
        byte[] source = File.ReadAllBytes(baseModel);
        string path = Path.Combine(tempDirectory, "bad-tokenizer.gguf");
        foreach (var (key, offset, value) in new (string, int, uint)[]
        {
            ("pad_id", 4, 0), ("bos_id", 4, 258), ("sep_id", 4, 260), ("merge_base", 4, 320),
            ("seed_base", 4, 400), ("merges", 16, 256), ("merges", 16, 298), ("merges", 16, 300)
        })
        {
            byte[] bytes = (byte[])source.Clone();
            byte[] field = Encoding.ASCII.GetBytes("capstone_sql.tokenizer." + key);
            int index = bytes.AsSpan().IndexOf(field);
            Require(index >= 0, $"Missing fixture field {key}");
            BinaryPrimitives.WriteUInt32LittleEndian(bytes.AsSpan(index + field.Length + offset), value);
            File.WriteAllBytes(path, bytes);
            try
            {
                GgufContract.ReadTokenizer(path);
            }
            catch (InvalidDataException)
            {
                continue;
            }
            throw new InvalidOperationException($"Accepted invalid tokenizer metadata {key} = {value}");
        }
    }

    private static string HexText(string hex) => Encoding.ASCII.GetString(Convert.FromHexString(hex));

    private static int[] Ints(string numbers) => numbers.Split(' ', StringSplitOptions.RemoveEmptyEntries)
        .Select(s => int.Parse(s, CultureInfo.InvariantCulture)).ToArray();

    private static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException(message);
    }
}
